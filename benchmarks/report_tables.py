"""Render the RESULTS.md tables straight from the measured artifacts (no hand-copied numbers).

python -m benchmarks.report_tables --store data > benchmarks/results/tables.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from common.storage import open_store

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "benchmarks/results"


def f(x, nd=3):
    return f"{x:.{nd}f}"


def cm_table(cm, labels) -> str:
    head = "| actual \\ predicted | " + " | ".join(labels) + " |\n|---|" + "---|" * len(labels) + "\n"
    return head + "\n".join(
        f"| **{lbl}** | " + " | ".join(str(v) for v in row) + " |" for lbl, row in zip(labels, cm, strict=True)
    )


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--store", default="data")
    args = p.parse_args()
    store = open_store(args.store)
    ptr = store.get_json("models/latest.json")
    m = store.get_json(f"{ptr['prefix']}/metrics.json")
    out = [f"<!-- generated by benchmarks/report_tables.py from model {m['version']} -->"]

    d = m["data"]
    out.append(
        f"Model version `{m['version']}` · snapshot (as_of) {d['as_of']} · {d['n_issues']} issues created "
        f"{d['created_period'][0]} → {d['created_period'][1]} ({', '.join(f'{k}: {v}' for k, v in d['by_repo'].items())}) "
        f"· train+evaluate+refit {m['duration_s']} s · then batch scoring {m['batch_scoring']['rows']} rows in "
        f"{m['batch_scoring']['duration_s']} s\n"
    )

    r = m["regression"]
    t = r["test"]
    out.append("### Regression: resolution time (days)\n")
    out.append(
        f"Target: {r['target']}. Train n={r['n_train']} (created {r['train_period'][0]} → {r['train_period'][1]}), "
        f"test n={r['n_test']} (created {r['test_period'][0]} → {r['test_period'][1]}). "
        f"Variant chosen on validation: `{r['chosen_variant']}` (val MAE: "
        + ", ".join(f"{k} {f(v['mae'])}" for k, v in r["validation"].items())
        + ").\n"
    )
    out.append("| model | MAE (days) | RMSE (days) |\n|---|---|---|")
    out.append(
        f"| median baseline (predict {f(t['baseline_median']['value_days'])} d) | {f(t['baseline_median']['mae'])} | {f(t['baseline_median']['rmse'])} |"
    )
    out.append(f"| RandomForestRegressor | {f(t['random_forest']['mae'])} | {f(t['random_forest']['rmse'])} |")
    out.append(
        f"| *ablation: + leaky post-hoc features (not served)* | {f(r['ablation_with_leaky_features']['mae'])} | {f(r['ablation_with_leaky_features']['rmse'])} |"
    )
    out.append(
        f"\nImprovement over baseline: MAE **{f(t['mae_improvement_pct'], 2)}%**, RMSE **{f(t['rmse_improvement_pct'], 2)}%**. "
        f"Test target: mean {f(r['test_target_distribution']['mean'], 2)} d, median {f(r['test_target_distribution']['median'], 2)} d, "
        f"{f(100 * r['test_target_distribution']['share_at_cap'], 1)}% at the 90-day cap.\n"
    )

    b = m["bucket"]
    lt, bt = b["test"]["logreg"], b["test"]["baseline_majority"]
    out.append("### Resolution bucket classification\n")
    out.append(
        f"Train n={b['n_train']} ({b['train_period'][0]} → {b['train_period'][1]}), test n={b['n_test']} "
        f"({b['test_period'][0]} → {b['test_period'][1]}). class_weight chosen on validation: `{b['chosen_class_weight']}` "
        f"(val macro-F1 {', '.join(f'{k}: {f(v)}' for k, v in b['validation_macro_f1_by_class_weight'].items())}).\n"
    )
    out.append("| model | accuracy | macro-F1 |\n|---|---|---|")
    out.append(f"| majority baseline (`{bt['majority_class']}`) | {f(bt['accuracy'])} | {f(bt['macro_f1'])} |")
    out.append(f"| LogisticRegression (TF-IDF + numeric) | {f(lt['accuracy'])} | {f(lt['macro_f1'])} |")
    la = b["ablation_with_leaky_features"]
    out.append(f"| *ablation: + leaky post-hoc features (not served)* | {f(la['accuracy'])} | {f(la['macro_f1'])} |")
    out.append(
        f"\nClass distribution: train {b['train_distribution']}, test {b['test_distribution']}.\n\nLogReg confusion matrix (test):\n"
    )
    out.append(cm_table(lt["confusion_matrix"], lt["labels"]))
    out.append(
        "\nPer-class (LogReg): "
        + "; ".join(
            f"`{k}` P={f(v['precision'], 2)} R={f(v['recall'], 2)} F1={f(v['f1'], 2)}"
            for k, v in lt["per_class"].items()
        )
    )
    out.append("\nMajority-baseline confusion matrix (test):\n")
    out.append(cm_table(bt["confusion_matrix"], bt["labels"]))

    c = m["category"]
    ct, cb = c["test"]["tfidf_logreg"], c["test"]["baseline_majority"]
    out.append("\n### Category classification (weak labels from area labels)\n")
    out.append(
        f"Train n={c['n_train']} ({c['train_period'][0]} → {c['train_period'][1]}), test n={c['n_test']} "
        f"({c['test_period'][0]} → {c['test_period'][1]}). Test distribution {c['test_distribution']}.\n"
    )
    out.append("| model | accuracy | macro-F1 |\n|---|---|---|")
    out.append(f"| majority baseline (`{cb['majority_class']}`) | {f(cb['accuracy'])} | {f(cb['macro_f1'])} |")
    out.append(f"| TF-IDF + LogisticRegression | {f(ct['accuracy'])} | {f(ct['macro_f1'])} |")
    out.append(
        "\nPer-class F1: " + "; ".join(f"`{k}` {f(v['f1'], 2)} (n={v['support']})" for k, v in ct["per_class"].items())
    )

    cl = json.loads((RES / "cold_load.json").read_text())
    before = json.loads((RES / "cold_load_before_batch_scoring.json").read_text())
    out.append("\n### Dashboard cold load\n")
    out.append(
        "| app | cold load median (min–max), s | warm rerun median, s | GitHub API calls per load |\n|---|---|---|---|"
    )
    for name, label in (("legacy", "legacy (fetch + train on load)"), ("new", "new (read lake + saved models)")):
        x = cl[name]
        out.append(
            f"| {label} | {f(x['cold_median_s'], 2)} ({f(x['cold_min_s'], 2)}–{f(x['cold_max_s'], 2)}) | {f(x['warm_median_s'], 2)} | {x['github_calls_per_cold_load']:g} |"
        )
    x = before["new"]
    out.append(
        f"| *new, first version (re-scored all issues on load)* | {f(x['cold_median_s'], 2)} ({f(x['cold_min_s'], 2)}–{f(x['cold_max_s'], 2)}) | {f(x['warm_median_s'], 2)} | {x['github_calls_per_cold_load']:g} |"
    )
    out.append(
        f"\nSpeed-up (legacy median / new median): **{f(cl['speedup_cold_median_x'], 2)}×**; {cl['trials']} trials each."
    )

    sched = RES / "scheduled_runs.json"
    if sched.exists():
        s = json.loads(sched.read_text())
        out.append("\n### Scheduled incremental runs (15-min cadence, local)\n")
        out.append("```json\n" + json.dumps(s, indent=2) + "\n```")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
